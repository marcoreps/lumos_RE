        print("Reverse sweep")

        # Avoid duplicate measurement at +half-span and immediately
        # begin travelling downward.
        for i in range(
            count - 1,
            -1,
            -1,
        ):

            offset = (
                low
                + i * sample_step
            )

            settling = (
                self.move_to_measurement_offset(
                    offset
                )
            )

            self.log_point(
                test="long_500um",
                direction="reverse",

                requested_offset_mm=(
                    offset
                ),

                settling=(
                    settling
                ),
            )

