def collect_device_info(
    logger,
):

    url = (
        f"http://{logger.ip}:"
        f"{logger.port}/device/info"
    )

    try:

        response = requests.get(
            url,
            timeout=logger.timeout,
        )

        response.raise_for_status()

        info = (
            response.json()
        )

        logger.metadata(
            "device_info_json",

            json.dumps(
                info,
                sort_keys=True,
            ),
        )

        for key in (
            "app_version",
            "ver_mcu_1",
            "ver_mcu_2",
            "dev_type",
            "laser_id",
            "hostname",
        ):

            if key in info:

                logger.metadata(
                    key,
                    info[key],
                )

    except Exception as exc:

        logger.metadata(
            "device_info_error",
            repr(exc),
        )


