def configure_encoder_only(mc):
    """
    Configure ONLY the TMC4671 analog encoder decoder.

    Deliberately omitted:
      - TMC6100 setup
      - Parker motor energization
      - open-loop alignment
      - Parker homing
      - endstop seeking
      - torque control
      - velocity control
      - position control
    """

    mc.write_register(
        TMC4671.REG.MODE_RAMP_MODE_MOTION,
        TMC4671.ENUM.MOTION_MODE_STOPPED,
    )

    # Explicitly remove any external motor-drive request.
    mc.write_register_field(
        TMC4671.FIELD.UD_EXT,
        0,
    )

    mc.write_register_field(
        TMC4671.FIELD.UQ_EXT,
        0,
    )

    # Keep the non-power-of-two multi-turn counter away from zero.
    mc.write_register_field(
        TMC4671.FIELD.AENC_DECODER_COUNT,
        AENC_SAFE_START,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_DECODER_MODE_120DEG_N90DEG,
        0,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_DECODER_PPR,
        AENC_PPR,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_0_SCALE,
        AENC_0_SCALE,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_0_OFFSET,
        AENC_0_OFFSET,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_1_SCALE,
        AENC_1_SCALE,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_1_OFFSET,
        AENC_1_OFFSET,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_2_SCALE,
        AENC_2_SCALE,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_2_OFFSET,
        AENC_2_OFFSET,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_0_SELECT,
        0,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_1_SELECT,
        1,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_2_SELECT,
        2,
    )

    mc.write_register_field(
        TMC4671.FIELD.AENC_DECODER_PHI_A_OFFSET,
        0,
    )

    time.sleep(0.25)


def read_encoder(mc):

    return u32(
        mc.read_register(
            TMC4671.REG.AENC_DECODER_COUNT
        )
    )


# ======================================================================
# Encoder measurement burst
# ======================================================================

def measure_encoder(
    mc,
    duration=0.20,
    interval=0.002,
):
    """
    Acquire a stationary burst of encoder readings.

    Returns both:
      - summary statistics
      - all raw counts and timestamps
    """

    raw_counts = []
    raw_times = []

    start_monotonic = time.monotonic()
    deadline = start_monotonic + duration

    while time.monotonic() < deadline:

        sample_time = time.monotonic()

        raw_counts.append(
            read_encoder(mc)
        )

        raw_times.append(
            sample_time
            - start_monotonic
        )

        time.sleep(interval)

    if not raw_counts:

        raise RuntimeError(
            "No encoder samples acquired"
        )

    center = int(
        round(
            statistics.median(
                raw_counts
            )
        )
    )

    deviations_um = [
        delta_um(value, center)
        for value in raw_counts
    ]

    if len(deviations_um) > 1:

        std_um = statistics.pstdev(
            deviations_um
        )

    else:

        std_um = 0.0

    pp_um = (
        max(deviations_um)
        - min(deviations_um)
    )

    return {
        "count": center,
        "samples": len(raw_counts),

        "std_um": std_um,
        "pp_um": pp_um,

        "raw_counts": raw_counts,
        "raw_times": raw_times,

        "start_monotonic": (
            start_monotonic
        ),
    }


# ======================================================================
# Encoder-confirmed settling
# ======================================================================

def wait_for_encoder_stable(
    mc,
    *,
    guard_s=0.15,
    stable_time_s=0.30,
    threshold_um=0.10,
    poll_s=0.010,
    timeout_s=10.0,
):
    """
    Wait until the external encoder has remained inside threshold_um
    peak-to-peak for stable_time_s continuously.

    A guard interval occurs first.

    Defaults therefore mean approximately:

        final motion
            |
            +-- 0.15 s minimum guard
            |
            +-- 0.30 s continuous stability
            |
            +-- acquisition

    Earliest possible measurement is therefore ~0.45 s after the final
    motion command completes.

    If the mechanism moves during the stable interval, the timer
    effectively starts over.
    """

    start = time.monotonic()

    # --------------------------------------------------------------
    # Initial guard interval
    # --------------------------------------------------------------

    while (
        time.monotonic() - start
        < guard_s
    ):

        read_encoder(mc)

        time.sleep(
            poll_s
        )

    # --------------------------------------------------------------
    # Stability window
    # --------------------------------------------------------------

    history = deque()

    while True:

        now = time.monotonic()

        count = read_encoder(
            mc
        )

        history.append(
            (now, count)
        )

        # Keep approximately one stable_time_s window.
        while (
            history
            and (
                now
                - history[0][0]
            ) > stable_time_s
        ):

            history.popleft()

        if len(history) >= 2:

            window_age = (
                now
                - history[0][0]
            )

            if (
                window_age
                >= stable_time_s * 0.95
            ):

                reference = (
                    history[0][1]
                )

                positions_um = [
                    delta_um(
                        value,
                        reference,
                    )
                    for _, value
                    in history
                ]

                span_um = (
                    max(positions_um)
                    - min(positions_um)
                )

                if (
                    span_um
                    <= threshold_um
                ):

                    return {
                        "settle_total_s":
                            now - start,

                        "settle_guard_s":
                            guard_s,

                        "stable_time_s":
                            window_age,

                        "stable_span_um":
                            span_um,

                        "stable_samples":
                            len(history),
                    }

        if (
            now - start
            > timeout_s
        ):

            raise RuntimeError(
                "Z axis failed to become "
                "encoder-stable within "
                f"{timeout_s:.1f} seconds"
            )

        time.sleep(
            poll_s
        )


