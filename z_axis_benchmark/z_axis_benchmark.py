def u32(value):
    return int(value) & 0xFFFFFFFF


def signed_delta_u32(a, b):
    """
    Signed 32-bit difference a-b, including wraparound handling.
    """

    delta = (
        u32(a) - u32(b)
    ) & 0xFFFFFFFF

    if delta & 0x80000000:
        delta -= 0x100000000

    return delta


def delta_um(a, b):
    return (
        signed_delta_u32(a, b)
        * UM_PER_COUNT
    )


